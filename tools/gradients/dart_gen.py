"""Render the tracked Dart preset registry from ``assets/icon/presets.json``."""

from __future__ import annotations

from pathlib import Path

import gradient_preset as gp

HEADER = """// GENERATED by tools/gradients/apply_gradient.py - DO NOT EDIT.
//
// Source: assets/icon/presets.json. Apply a preset with the `gradient-preset`
// skill; this file and the registry are rewritten together, never by hand.

import 'package:material_ui/material_ui.dart';

/// One applied gradient preset: app background, Home/Me glow and nav pill.
final class GradientPreset {
  /// Creates the preset registered as [id].
  const new({
    required this.id,
    required this.name,
    required this.base,
    required this.accent,
    required this.iconAsset,
    required this.glow,
  });

  /// Stable slug used by [AppGradientPresets.byId].
  final String id;

  /// Display name; defaults to [id].
  final String name;

  /// Opaque page background color.
  final Color base;

  /// Dominant color of the icon, used as the accent when the user asks for it.
  final Color accent;

  /// Legacy icon declared in `pubspec.yaml`, shown in the app icon picker.
  final String iconAsset;

  /// One radial gradient per glow layer, painted behind the Home header,
  /// inside the Me identity card and inside the nav pill. The same order as the
  /// icon's layers, so the wash keeps the icon's colors.
  final List<RadialGradient> glow;
}

/// Every applied preset, sorted by id.
abstract final class AppGradientPresets {
  /// All presets in `assets/icon/presets.json`.
  static const List<GradientPreset> all = [
"""

FOOTER = """  ];

  /// The preset with [id], or null when it was never applied.
  static GradientPreset? byId(String id) {
    for (final preset in all) {
      if (preset.id == id) return preset;
    }
    return null;
  }

  static const String _activeId = '{active_id}';

  /// Preset selected by the active id in `assets/icon/presets.json`.
  static final GradientPreset active = byId(_activeId)!;
}
"""


def render_dart(registry: dict) -> str:
    """Return the Dart source for the applied presets in [registry]."""
    presets = registry.get("presets")
    if not isinstance(presets, dict) or not presets:
        raise gp.PresetError("assets/icon/presets.json holds no presets")
    ordered = [presets[key] for key in sorted(presets)]
    active_id = registry.get("active") or ordered[0]["id"]
    if active_id not in presets:
        raise gp.PresetError(
            f"assets/icon/presets.json is active={active_id!r}, "
            "which is not one of its presets"
        )

    blocks = [_preset_block(preset) for preset in ordered]
    return HEADER + "".join(blocks) + FOOTER.replace("{active_id}", active_id)


def _preset_block(preset: dict) -> str:
    accent = preset.get("accent")
    if not accent:
        raise gp.PresetError(
            f"preset {preset['id']!r} has no derived accent; "
            "run apply_gradient.py --refresh"
        )
    icon = preset.get("icon") or {}
    icon_asset = icon.get("legacy")
    if not icon_asset:
        raise gp.PresetError(
            f"preset {preset['id']!r} has no icon.legacy for the icon picker"
        )
    return (
        "    GradientPreset(\n"
        f"      id: '{preset['id']}',\n"
        f"      name: '{preset['name']}',\n"
        f"      base: Color({gp.argb_hex(preset['base'])}),\n"
        f"      accent: Color({gp.argb_hex(accent)}),\n"
        f"      iconAsset: '{icon_asset}',\n"
        f"{_gradient_list('glow', preset['glow'])}"
        "    ),\n"
    )


def _gradient_list(name: str, gradients: list[dict]) -> str:
    body = "".join(f"{_gradient(gradient, indent=8)},\n" for gradient in gradients)
    return f"      {name}: [\n{body}      ],\n"


def _gradient(gradient: dict, indent: int = 6) -> str:
    x, y = gradient["center"]
    stops = ", ".join(_decimal(stop["position"]) for stop in gradient["stops"])
    colors = [
        f"Color({gp.argb_hex(stop['color'], stop['alpha'])})"
        for stop in gradient["stops"]
    ]
    field = " " * (indent + 2)
    one_line = f"{field}colors: [{', '.join(colors)}],"
    if len(one_line) <= 80:
        color_block = f"{one_line}\n"
    else:
        color_block = f"{field}colors: [\n" + "".join(
            f"{field}  {color},\n" for color in colors
        ) + f"{field}],\n"
    return (
        " " * indent
        + "RadialGradient(\n"
        f"{field}center: Alignment({_decimal(x)}, {_decimal(y)}),\n"
        f"{field}radius: {_decimal(gradient['radius'])},\n"
        f"{color_block}"
        f"{field}stops: [{stops}],\n"
        + " " * indent
        + ")"
    )


def _decimal(value: float) -> str:
    text = f"{value:.4f}".rstrip("0")
    return text[:-1] if text.endswith(".") else text


def write_dart(registry: dict, path: Path) -> None:
    """Write the generated Dart file atomically enough for `dart format`."""
    path.write_text(render_dart(registry), encoding="utf8")
